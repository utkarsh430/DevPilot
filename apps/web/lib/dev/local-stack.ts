// ── Secrets + the assembled value set ───────────────────────────────────────

export type LocalSecrets = {
  DEVPILOT_RUNNER_REGISTRATION_KEY: string;
  SECRETS_ENCRYPTION_KEY: string;
  INNGEST_EVENT_KEY: string;
  INNGEST_SIGNING_KEY: string;
};

/** Every value is chosen so `serializeEnvValue` never has to quote or refuse
 *  it: hex for the runner and Inngest keys (the Inngest server insists on hex
 *  for the signing key; the SDK form carries the `signkey-prod-` prefix it
 *  strips before hashing), and for the encryption key the exact shape
 *  `validateEncryptionKey` checks (32 random bytes, base64). */
export function generateLocalSecrets(random: (bytes: number) => Buffer): LocalSecrets {
  return {
    DEVPILOT_RUNNER_REGISTRATION_KEY: random(32).toString("hex"),
    SECRETS_ENCRYPTION_KEY: random(32).toString("base64"),
    INNGEST_EVENT_KEY: random(32).toString("hex"),
    INNGEST_SIGNING_KEY: `signkey-prod-${random(32).toString("hex")}`,
  };
}

/** Everything `setup:local` offers to `fillEnvTemplate`. The tenant id is
 *  included only when the account bootstrap produced one — a blank entry would
 *  "set" a blank, which reads as configured and is not. */
export function buildLocalEnvValues(input: {
  supabase: SupabaseLocalEnv;
  secrets: LocalSecrets;
  tenantId?: string;
  /** From `runnerNameFor(os.hostname())`; omitted by callers that have no host. */
  runnerName?: string;
}): Record<string, string> {
  const values: Record<string, string> = {
    NEXT_PUBLIC_SUPABASE_URL: input.supabase.NEXT_PUBLIC_SUPABASE_URL,
    NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: input.supabase.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,
    SUPABASE_SECRET_KEY: input.supabase.SUPABASE_SECRET_KEY,
    DATABASE_URL: input.supabase.DATABASE_URL,
    UPSTASH_REDIS_REST_URL: LOCAL_REDIS_REST_URL,
    UPSTASH_REDIS_REST_TOKEN: LOCAL_REDIS_REST_TOKEN,
    DEVPILOT_RUNNER_REGISTRATION_KEY: input.secrets.DEVPILOT_RUNNER_REGISTRATION_KEY,
    SECRETS_ENCRYPTION_KEY: input.secrets.SECRETS_ENCRYPTION_KEY,
    // Durable mode: explicit cloud routing at the LOCAL self-hosted server.
    INNGEST_DEV: "0",
    INNGEST_BASE_URL: LOCAL_INNGEST_URL,
    INNGEST_EVENT_KEY: input.secrets.INNGEST_EVENT_KEY,
    INNGEST_SIGNING_KEY: input.secrets.INNGEST_SIGNING_KEY,
    NEXT_PUBLIC_APP_URL: LOCAL_APP_URL,
    LOCAL_CC_ENGINE_URL: LOCAL_APP_URL,
    // Instant sign-in: the magic link only ever lands in Mailpit on this
    // machine, so the login page signs the visitor in directly instead.
    // Doubly gated on a loopback Supabase URL (lib/auth/local-signin.ts).
    DEVPILOT_LOCAL_PASSWORDLESS: "1",
  };
  if (input.supabase.NEXT_PUBLIC_LOCAL_MAIL_URL) {
    values.NEXT_PUBLIC_LOCAL_MAIL_URL = input.supabase.NEXT_PUBLIC_LOCAL_MAIL_URL;
  }
  if (input.tenantId) values.DEVPILOT_RUNNER_TENANT_ID = input.tenantId;
  if (input.runnerName) values.DEVPILOT_RUNNER_NAME = input.runnerName;
  return values;
}

// ── Preflight predicates ────────────────────────────────────────────────────

/** True only for a loopback host — the one case where `dev:local` may answer
 *  "Redis is down" by starting the compose stack. A real Upstash URL is never
 *  "fixed" with Docker. Hostname comparison, never a prefix match. */
export function isLocalRedisUrl(url: string): boolean {
  try {
    const host = new URL(url).hostname;
    return host === "127.0.0.1" || host === "localhost" || host === "[::1]" || host === "::1";
  } catch {
    return false;
  }
}

/** The Upstash REST `GET /ping` answer, as the app's own `validateRedis` reads it. */
export function isPong(body: unknown): boolean {
  return !!body && typeof body === "object" && (body as { result?: unknown }).result === "PONG";
}

export type ClaudeAuthState = "logged-in" | "logged-out" | "unknown";

export type SupabaseContainerState = "absent" | "running" | "stopped";

/** What to do when the Supabase API is not answering, given what Docker says
 *  about the database container. The reboot race this encodes: Docker Desktop
 *  auto-restarts the containers on its own after a reboot or an engine
 *  restart, and `supabase start` run into a database that is still booting
 *  fails with "container is not ready: starting" - which is not a failure to
 *  act on, it is a reason to wait. */
export function decideSupabaseBringUp(state: SupabaseContainerState): "start" | "wait-then-start" {
  return state === "running" ? "wait-then-start" : "start";
}

/** Map `docker ps -a --format {{.Status}}` for the db container (or "" when
 *  there is none) onto the three states above. */
export function classifySupabaseContainer(status: string | null): SupabaseContainerState {
  if (status === null || status.trim() === "") return "absent";
  return /^Up\b/i.test(status.trim()) ? "running" : "stopped";
}

/** `claude auth status` prints a JSON object with `loggedIn`. Anything else —
 *  an older CLI, a crash, no output — is `unknown`, which the scripts report as
 *  a warning rather than a verdict. */
export function classifyClaudeAuth(stdout: string): ClaudeAuthState {
  const start = stdout.indexOf("{");
  const end = stdout.lastIndexOf("}");
  if (start === -1 || end === -1 || end < start) return "unknown";
  try {
    const parsed: unknown = JSON.parse(stdout.slice(start, end + 1));
    const loggedIn = (parsed as { loggedIn?: unknown })?.loggedIn;
    if (loggedIn === true) return "logged-in";
    if (loggedIn === false) return "logged-out";
    return "unknown";
  } catch {
    return "unknown";
  }
}

/** Major version out of `process.versions.node` (`"24.13.0"` → 24). */
export function nodeMajor(version: string): number {
  const n = Number.parseInt(version.split(".")[0] ?? "", 10);
  return Number.isFinite(n) ? n : 0;
}

export const MIN_NODE_MAJOR = 20;

// ── What survives a restart ─────────────────────────────────────────────────
//
// The database (Supabase volumes), the queue (the compose volume), the
// workspaces (WORKSPACE_ROOT, outside the repo) and - once `dev-inngest.mjs`
// runs the dev server with `--persist` - every in-flight durable run all
// outlive a restart on their own. The three things below are the ones that
// did NOT, and each is a small rule rather than a mechanism.

/** A stable runner name, so every start re-registers the SAME `runners` row
 *  (the register route upserts on `tenant_id,name`) instead of minting
 *  `local-cc-darwin-<pid>` per start and leaving a trail of offline rows for
 *  the watchdog to sweep. */
export function runnerNameFor(hostname: string): string {
  const slug = hostname
    .toLowerCase()
    .replace(/[^a-z0-9.-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return slug.length > 0 ? `local-cc-${slug}` : "local-cc-local";
}

/** Where `setup:local` keeps a copy of `.env.local`, OUTSIDE the repo. The file
 *  is gitignored, and a `git clean -fdx` (or a re-clone into the same place)
 *  takes it with it - including `SECRETS_ENCRYPTION_KEY`, without which every
 *  secret already stored in the local database is unreadable forever. Keyed on
 *  the repo path so two clones do not share one backup. */
export function envBackupPath(home: string, repoDir: string): string {
  const key = createHash("sha256").update(repoDir).digest("hex").slice(0, 12);
  return join(home, ".devpilot", "env-backups", `${key}.env.local`);
}

/** `pnpm install` has not been run since the lockfile last changed (or at all).
 *  pnpm stamps `node_modules/.modules.yaml` on every install, so its mtime is
 *  the install time. A warning, not a gate - a developer mid-edit knows. */
export function isInstallStale(lockMtimeMs: number | null, modulesMtimeMs: number | null): boolean {
  if (lockMtimeMs === null) return false;
  if (modulesMtimeMs === null) return true;
  return lockMtimeMs > modulesMtimeMs;
}

// ── GitHub OAuth (the one credential a clone cannot generate) ───────────────
//
// Every project is a GitHub repo (both New-project flows need a token), and
// the token comes from Supabase Auth's GitHub provider - which on a LOCAL
// Supabase means the operator's OWN OAuth App, with the local GoTrue as its
// callback. `supabase/config.toml` enables the provider and reads the two
// values from `supabase/.env` (which the CLI loads), so the app can be
// registered once and the values pasted into `setup:local`.

export const SUPABASE_DOTENV_GITHUB_KEYS = [
  "SUPABASE_AUTH_EXTERNAL_GITHUB_CLIENT_ID",
  "SUPABASE_AUTH_EXTERNAL_GITHUB_SECRET",
] as const;

export type GithubOAuthApp = { clientId: string; clientSecret: string };

/** The two lines GoTrue reads (via config.toml's `env()`), for `supabase/.env`. */
export function buildSupabaseDotenvValues(app: GithubOAuthApp): Record<string, string> {
  return {
    SUPABASE_AUTH_EXTERNAL_GITHUB_CLIENT_ID: app.clientId.trim(),
    SUPABASE_AUTH_EXTERNAL_GITHUB_SECRET: app.clientSecret.trim(),
  };
}

/** The same app, for the web app's own refresh-token path (`.env.local`). */
export function buildGithubEnvValues(app: GithubOAuthApp): Record<string, string> {
  return {
    GITHUB_OAUTH_CLIENT_ID: app.clientId.trim(),
    GITHUB_OAUTH_CLIENT_SECRET: app.clientSecret.trim(),
  };
}

/** The callback GitHub must be told about: the LOCAL GoTrue, not the app. */
export function githubCallbackUrl(supabaseApiUrl: string): string {
  return `${supabaseApiUrl.replace(/\/+$/, "")}/auth/v1/callback`;
}

/** Printed by setup when no GitHub app is configured yet - the exact fields,
 *  because a wrong callback URL fails at the end of the dance with GitHub's
 *  generic "redirect_uri mismatch". */
export function githubOauthHowto(supabaseApiUrl: string, appUrl: string): string[] {
  return [
    "To connect repos (every project is a GitHub repo), register a GitHub OAuth App once:",
    "  https://github.com/settings/developers → OAuth Apps → New OAuth App",
    `    Homepage URL:               ${appUrl}`,
    `    Authorization callback URL: ${githubCallbackUrl(supabaseApiUrl)}`,
    "  then: pnpm setup:local --github-client-id <id> --github-client-secret <secret>",
    "  (writes supabase/.env + .env.local and restarts the local Supabase so GoTrue picks it up)",
  ];
}
