// The local stack as data — the pure half of `scripts/setup-local.mjs` and
// `scripts/dev-local.mjs`. Everything here is a string or a decision; the
// scripts own the processes, sockets and files.
//
// Why these exist at all: a fresh clone used to need an Upstash account, a
// hand-assembled `.env.local`, a tenant uuid looked up in Studio, and the
// knowledge that four processes start in a fixed order. Each of those is now a
// value or a check in this module, so the two scripts stay thin and the rules
// are unit-tested (`__tests__/local-stack.test.ts`).

import { createHash } from "node:crypto";
import { join } from "node:path";

export const LOCAL_APP_URL = "http://127.0.0.1:3000";
export const LOCAL_INNGEST_URL = "http://127.0.0.1:8288";

/** The Upstash-compatible REST front for the local Redis that
 *  `infra/local/docker-compose.yml` runs. Loopback-bound; the token is a fixed,
 *  published, local-only value — the same posture as Supabase's well-known
 *  local keys. A test pins the compose file to these two constants. */
export const LOCAL_REDIS_REST_URL = "http://127.0.0.1:8079";
export const LOCAL_REDIS_REST_TOKEN = "devpilot-local-dev-token";

// ── Inngest: the DURABLE local server, not the dev server ───────────────────
//
// `inngest dev` keeps the queue and every in-flight run IN MEMORY; `--persist`
// was measured to keep only the history (a sleeping run came back after a
// restart as "Running" with no job behind it, forever). `inngest start` is the
// self-hosted server: queue + run state in Redis (the compose one, db 1, on
// its own loopback port), history in SQLite, and it needs an event key and a
// signing key - both generated by `setup:local`. The SDK picks that server
// only when `INNGEST_DEV` is EXPLICITLY `0` (unset under `next dev` infers
// the dev server), so that value is written too.

export const LOCAL_INNGEST_REDIS_URI = "redis://127.0.0.1:16379/1";
// 127.0.0.1, not localhost: `dev:local` binds the app to IPv4 loopback only
// (so instant sign-in is never reachable from the Wi-Fi), and `localhost` may
// resolve to ::1 first.
export const INNGEST_SDK_URL = "http://127.0.0.1:3000/api/inngest";

export type InngestMode = "server" | "dev";

/** `server` only when the env says so explicitly AND both keys are present;
 *  anything else is the keyless dev server (what a hand-written `.env.local`
 *  from before durable mode has). */
export function inngestModeFor(env: Record<string, string | undefined>): InngestMode {
  const dev = (env.INNGEST_DEV ?? "").trim().toLowerCase();
  const explicitCloud = dev === "0" || dev === "false";
  const keys = (env.INNGEST_EVENT_KEY ?? "").trim() && (env.INNGEST_SIGNING_KEY ?? "").trim();
  return explicitCloud && keys ? "server" : "dev";
}

/** The SDK accepts `signkey-<env>-<hex>` and hashes the hex; the server wants
 *  the hex alone ("must be hex string with even number of chars"). */
export function stripSigningKeyPrefix(key: string): string {
  return key.trim().replace(/^signkey-[\w]+-/, "");
}

/** argv + child env for `inngest start`. Keys go through the ENVIRONMENT, which
 *  the server reads (verified: it boots with INNGEST_EVENT_KEY/INNGEST_SIGNING_KEY
 *  set and no flags, and refuses with "signing-key is required" without), so
 *  they never appear in `ps`. */
export function inngestServerSpec(
  env: Record<string, string | undefined>,
  opts: { dataDir: string; sdkUrl?: string; redisUri?: string },
): { args: string[]; env: Record<string, string> } {
  return {
    args: [
      "start",
      "-u",
      opts.sdkUrl ?? INNGEST_SDK_URL,
      "--sqlite-dir",
      opts.dataDir,
      "--redis-uri",
      opts.redisUri ?? LOCAL_INNGEST_REDIS_URI,
      "--poll-interval",
      "5",
    ],
    env: {
      INNGEST_EVENT_KEY: (env.INNGEST_EVENT_KEY ?? "").trim(),
      INNGEST_SIGNING_KEY: stripSigningKeyPrefix(env.INNGEST_SIGNING_KEY ?? ""),
    },
  };
}

